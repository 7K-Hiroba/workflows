#!/usr/bin/env python3
"""Build deterministic source or evidence-bound catalog/template indexes."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.metadata import discover, release_artifacts, verified_artifact, write_if_changed  # noqa: E402

PACKAGE_MEDIA = "application/vnd.inari.catalog.package.v1+yaml"
TEMPLATE_MEDIA = "application/vnd.inari.template.v1"


def document(api_kind: str, key: str, entries: list[dict[str, Any]]) -> str:
    body = {"apiVersion": "inari.dev/v1alpha1", "kind": api_kind, key: entries}
    return "# GENERATED by scripts/build-indexes.py; do not edit.\n" + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def build(root: Path, evidence_path: Path | None, registry_prefix: str = "ghcr.io/7k-hiroba") -> dict[str, str]:
    plan = discover(root)
    app = plan["app"]
    source_sha = None
    artifacts = None
    if evidence_path:
        source_sha, artifacts = release_artifacts(evidence_path)

    packages = []
    for component in plan["components"]:
        if component["kind"] != "package":
            continue
        name = component["name"]
        repository = f"{registry_prefix}/{app}/catalog/{name}"
        entry = {
            "name": name,
            "version": component["version"],
            "channel": component["channel"],
            "type": component["packageType"],
            "description": component["description"],
            "category": component["category"],
            "ociRef": f"{repository}:{component['version']}",
            "channelRef": f"{repository}:{component['channel']}",
        }
        if component.get("observability"):
            entry["observability"] = component["observability"]
        if artifacts is not None and source_sha is not None:
            evidence = verified_artifact(artifacts, f"catalog/{name}", PACKAGE_MEDIA, source_sha, repository=repository)
            entry.update({
                "ociRef": f"{repository}@{evidence['digest']}",
                "digest": evidence["digest"],
                "mediaType": PACKAGE_MEDIA,
                "sourceSha": source_sha,
                "signature": evidence["signature"],
                "provenance": evidence["provenance"],
                "testEvidence": evidence["testEvidence"],
            })
        packages.append(entry)

    templates = []
    for component in plan["components"]:
        if component["kind"] != "template":
            continue
        name = component["name"]
        repository = f"{registry_prefix}/{app}/templates/{name}"
        entry = {
            "name": name,
            "version": component["version"],
            "channel": component["channel"],
            "description": component["description"],
            "kind": component["templateKind"],
            "ociRef": f"{repository}:{component['version']}",
            "channelRef": f"{repository}:{component['channel']}",
        }
        if artifacts is not None and source_sha is not None:
            evidence = verified_artifact(artifacts, f"template/{name}", TEMPLATE_MEDIA, source_sha, repository=repository)
            entry.update({
                "ociRef": f"{repository}@{evidence['digest']}",
                "digest": evidence["digest"],
                "mediaType": TEMPLATE_MEDIA,
                "sourceSha": source_sha,
                "signature": evidence["signature"],
                "provenance": evidence["provenance"],
                "testEvidence": evidence["testEvidence"],
            })
        templates.append(entry)

    return {
        "catalog.yaml": document("CatalogIndex", "packages", packages),
        "templates.yaml": document("TemplateIndex", "templates", templates),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--release-evidence", type=Path)
    parser.add_argument("--registry-prefix", default="ghcr.io/7k-hiroba")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        outputs = build(args.root.resolve(), args.release_evidence, args.registry_prefix)
    except (KeyError, ValueError, OSError) as exc:
        print(f"::error::{exc}", file=sys.stderr)
        return 1
    errors: list[str] = []
    for name, content in outputs.items():
        write_if_changed(args.root / name, content, args.check, errors)
    for error in errors:
        print(f"::error::{error}")
    if errors:
        return 1
    print("catalog.yaml and templates.yaml are in sync" if args.check else "generated catalog.yaml and templates.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
