#!/usr/bin/env python3
"""Render chart and kro observability outputs from canonical assets."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.metadata import load_config, load_yaml, write_if_changed  # noqa: E402

HEADER = "# GENERATED by scripts/render-observability.py; DO NOT EDIT.\n"


def dump_document(value: dict[str, Any]) -> str:
    return yaml.safe_dump(value, sort_keys=False, allow_unicode=True)


def json_block(value: Any, indent: int) -> str:
    raw = json.dumps(value, indent=2, sort_keys=True) + "\n"
    prefix = " " * indent
    return "".join(prefix + line + "\n" for line in raw.splitlines())


def chart_configmap(app: str, dashboard: dict[str, Any], content: dict[str, Any]) -> str:
    uid = dashboard["uid"]
    resource = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": uid,
            "namespace": "{{ .Release.Namespace }}",
            "labels": {"app.kubernetes.io/name": app, "grafana_dashboard": "1"},
            "annotations": {"inari.dev/dashboard-uid": uid},
        },
        "data": {f"{uid}.json": json.dumps(content, indent=2, sort_keys=True) + "\n"},
    }
    return HEADER + "{{- if .Values.observability.enabled }}\n" + dump_document(resource) + "{{- end }}\n"


def chart_rules(app: str, rules: dict[str, Any]) -> str:
    resource = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": app + "-rules",
            "namespace": "{{ .Release.Namespace }}",
            "labels": {"app.kubernetes.io/name": app},
        },
        "spec": {"groups": rules.get("groups", [])},
    }
    return HEADER + "{{- if and .Values.observability.enabled .Values.observability.rules.enabled }}\n" + dump_document(resource) + "{{- end }}\n"


def kro_resource_id(prefix: str, value: str) -> str:
    """Return a lower-camel-case identifier accepted by KRO's CEL parser."""
    words = [word for word in re.split(r"[^a-zA-Z0-9]+", value) if word]
    return prefix + "".join(word[0].upper() + word[1:] for word in words)


def kro_json(value: dict[str, Any]) -> str:
    """Preserve Grafana interpolation markers as CEL string literals in a pack."""
    raw = json.dumps(value, indent=2, sort_keys=True) + "\n"
    return re.sub(r"\$\{[^{}]+\}", lambda match: "${" + json.dumps(match.group(0)) + "}", raw)


def pack_resource(resource_id: str, template: dict[str, Any], include: str | None = None) -> dict[str, Any]:
    resource: dict[str, Any] = {"id": resource_id, "template": template}
    if include:
        resource["includeWhen"] = [include]
    return resource


def render_pack(app: str, manifest: dict[str, Any], dashboards: list[tuple[dict[str, Any], dict[str, Any]]], rules: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    folder = manifest["folder"]
    spec = {
        "org": "string | required=true",
        "namespace": "string | default=\"monitoring\"",
        "app": f"string | default=\"{app}\"",
        "team": "string | required=true",
        "folder": f"string | default=\"{folder}\"",
        "datasource": "string | required=true",
        "render": "string | default=\"all\"",
        "rulesLocal": "boolean | default=true",
        "rulesCentral": "boolean | default=true",
    }
    resources: list[dict[str, Any]] = []
    folder_resource = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {"name": "${schema.spec.app}-folder", "namespace": "${schema.spec.namespace}"},
        "data": {
            "folder.yaml": dump_document({
                "title": "${schema.spec.folder}",
                "org": "${schema.spec.org}",
                "team": "${schema.spec.team}",
            }),
        },
    }
    resources.append(pack_resource("folder", folder_resource, '${schema.spec.render == "all" || schema.spec.render == "dashboards"}'))
    for dashboard, content in dashboards:
        uid = dashboard["uid"]
        template = {
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {"name": uid, "namespace": "${schema.spec.namespace}", "labels": {"grafana_dashboard": "1"}},
            "data": {f"{uid}.json": kro_json(content)},
        }
        resources.append(pack_resource(kro_resource_id("dashboard", uid), template, '${schema.spec.render == "all" || schema.spec.render == "dashboards"}'))
    for entry, content in rules:
        evaluation = entry["evaluation"]
        template = {
            "apiVersion": "monitoring.coreos.com/v1",
            "kind": "PrometheusRule",
            "metadata": {"name": "${schema.spec.app}-" + evaluation, "namespace": "${schema.spec.namespace}"},
            "spec": {"groups": content.get("groups", [])},
        }
        include = f'${{schema.spec.render == "all" || schema.spec.render == "rules-{evaluation}"}}'
        resources.append(pack_resource(kro_resource_id("rules", evaluation), template, include))
    rgd = {
        "apiVersion": "kro.run/v1alpha1",
        "kind": "ResourceGraphDefinition",
        "metadata": {"name": app + "-observability"},
        "spec": {
            "schema": {
                "apiVersion": "v1alpha1",
                "kind": "ObservabilityPack",
                "spec": spec,
                "status": {"ready": "${folder.metadata.name != \"\"}"},
            },
            "resources": resources,
        },
    }
    return HEADER + dump_document(rgd)


def render(root: Path) -> dict[Path, str]:
    config = load_config(root)
    settings = config["observability"]
    app = config["app"]
    observability_root = root / settings["path"]
    manifest = load_yaml(observability_root / "observability.yaml")

    dashboards: list[tuple[dict[str, Any], dict[str, Any]]] = []
    for dashboard in manifest.get("dashboards", []):
        path = observability_root / dashboard["file"]
        if not path.is_file():
            raise ValueError(f"dashboard asset not found: {path}")
        dashboards.append((dashboard, json.loads(path.read_text(encoding="utf-8"))))
    rules: list[tuple[dict[str, Any], dict[str, Any]]] = []
    for entry in manifest.get("rules", []):
        path = observability_root / entry["file"]
        if not path.is_file():
            raise ValueError(f"rule asset not found: {path}")
        parsed = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(parsed, dict):
            raise ValueError(f"rule asset must be a mapping: {path}")
        rules.append((entry, parsed))

    chart = root / settings["chart"]
    pack = root / settings["package"]
    outputs: dict[Path, str] = {}
    if dashboards:
        outputs[chart / "templates/observability/dashboards.yaml"] = "\n---\n".join(
            chart_configmap(app, dashboard, content) for dashboard, content in dashboards
        )
    if rules:
        combined = {"groups": [group for _, content in rules for group in content.get("groups", [])]}
        outputs[chart / "templates/observability/rules.yaml"] = chart_rules(app, combined)
    outputs[chart / "inari/observability.yaml"] = HEADER + dump_document(manifest)
    outputs[pack / "rgd.yaml"] = render_pack(app, manifest, dashboards, rules)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        outputs = render(root)
    except (OSError, KeyError, ValueError, yaml.YAMLError, json.JSONDecodeError) as exc:
        print(f"::error::{exc}", file=sys.stderr)
        return 1
    errors: list[str] = []
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(path, content, args.check, errors)
    for error in errors:
        print(f"::error::{error}")
    if errors:
        return 1
    print(f"observability outputs are in sync ({len(outputs)} files)" if args.check else f"generated {len(outputs)} observability files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
